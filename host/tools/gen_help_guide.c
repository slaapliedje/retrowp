#include <stdio.h>
#include <stdlib.h>
#include "types.h"
#include "help_doc.h"

/* Host-only build tool (M9 Phase 6): converts a docs/help/ *.help source
   file into a real AmigaGuide (.guide) document, reusing the SAME
   portable parser (platform/common/help_doc.c) app_shell.c's own pager
   uses -- not a second, hand-rolled parser that could drift out of sync
   with help_doc.c's real leniency rules. This is a genuine, low-risk
   export, not the .HYP research spike's own "worth pursuing later, not
   attempted now" conclusion (docs/help.md): AmigaGuide is plain text
   interpreted directly by amigaguide.library/Multiview, no external
   compiler dependency the way ST Guide's `hcp` needs one, and its real
   syntax (verified against this project's own installed
   amigaguide.library and the WB3.1 fixture's own genuine
   Locale/Help/english/Sys/amigaguide.guide, not just recalled from
   memory) is a close, deliberate match to this project's own
   `{label|target}` format already:
     `@node <name> "<title>"` / `@endnode`        -- identical shape
     `@{"<label>" link <target>}`                  -- one mechanical
                                                        transform from
                                                        `{<label>|<target>}`
   See docs/amiga-platform.md's Phase 6 section for the on-target
   verification (real amigaguide.library + MultiView under amiberry).

   Usage: gen_help_guide <input.help> <output.guide> <database-name>
   Mirrors gen_help_header.c's own plain-C89/POSIX-stdio-only shape,
   built with the host cc under RELAXED_CFLAGS -- but unlike that tool
   (which never parses its input, just copies bytes), this one links
   against the real portable parser (help_doc.o + strpool.o + the host
   platform stub's mem_host.o for mem_alloc/mem_free), so it can walk
   the real node/line graph instead of re-deriving the format by hand. */

static u8 *read_whole_file(const char *path, u32 *out_len)
{
    FILE *f;
    long size;
    u8 *buf;

    f = fopen(path, "rb");
    if (f == NULL) return NULL;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }
    size = ftell(f);
    if (size < 0 || fseek(f, 0, SEEK_SET) != 0) { fclose(f); return NULL; }

    buf = (u8 *)malloc((size_t)size + 1);
    if (buf == NULL) { fclose(f); return NULL; }
    if (size > 0 && fread(buf, 1, (size_t)size, f) != (size_t)size) {
        free(buf);
        fclose(f);
        return NULL;
    }
    fclose(f);

    *out_len = (u32)size;
    return buf;
}

/* AmigaGuide's own escape for a literal '"' or '@' inside quoted text
   (verified against hcp/AmigaGuide-family conventions: backslash-
   escape, the same idiom this project's own docs/help.md notes for
   ST Guide's near-identical @{"text" link name} syntax) -- defensive:
   no character in this project's own current help content actually
   needs it, but a future author's prose might. */
static void write_escaped(FILE *out, const u8 *bytes, u32 len)
{
    u32 i;
    for (i = 0; i < len; i++) {
        if (bytes[i] == '"' || bytes[i] == '@' || bytes[i] == '\\') fputc('\\', out);
        fputc((int)bytes[i], out);
    }
}

int main(int argc, char **argv)
{
    u8 *source;
    u32 source_len;
    wp_help_doc doc;
    FILE *out;
    u32 ni;

    if (argc != 4) {
        fprintf(stderr, "usage: %s <input.help> <output.guide> <database-name>\n", argv[0]);
        return 1;
    }

    source = read_whole_file(argv[1], &source_len);
    if (source == NULL) {
        fprintf(stderr, "gen_help_guide: cannot read %s\n", argv[1]);
        return 1;
    }

    if (wp_help_doc_parse(source, source_len, &doc) != WP_OK) {
        fprintf(stderr, "gen_help_guide: failed to parse %s\n", argv[1]);
        free(source);
        return 1;
    }
    free(source);

    out = fopen(argv[2], "w");
    if (out == NULL) {
        fprintf(stderr, "gen_help_guide: cannot open %s for writing\n", argv[2]);
        wp_help_doc_free(&doc);
        return 1;
    }

    fprintf(out, "@database \"%s\"\n", argv[3]);
    fprintf(out, "@rem Generated by host/tools/gen_help_guide.c from %s -- do not edit by hand.\n",
            argv[1]);
    fprintf(out, "@wordwrap\n\n");

    for (ni = 0; ni < doc.node_count; ni++) {
        const wp_help_node *node = &doc.nodes[ni];
        const u8 *name = wp_strpool_get(&doc.text, node->name);
        const u8 *title = wp_strpool_get(&doc.text, node->title);
        u32 li;

        /* Node names are bare identifiers in every real node this
           project's help content has ever had (a `{label|target}`
           link's target span is delimited by '|'/'}', so it can't
           contain either, but COULD in principle contain a space) --
           quoted defensively only when one actually does, matching
           AmigaGuide's own real support for a quoted @node name. */
        fputs("@node ", out);
        {
            wp_bool has_space = WP_FALSE;
            u32 k;
            for (k = 0; k < node->name.length; k++) {
                if (name[k] == ' ') { has_space = WP_TRUE; break; }
            }
            if (has_space) {
                fputc('"', out);
                write_escaped(out, name, node->name.length);
                fputc('"', out);
            } else {
                fwrite(name, 1, node->name.length, out);
            }
        }
        fputs(" \"", out);
        write_escaped(out, title, node->title.length);
        fputs("\"\n", out);

        for (li = 0; li < node->line_count; li++) {
            const wp_help_line *line = &node->lines[li];

            if (line->kind == (u8)WP_HELP_LINE_TEXT) {
                const u8 *text = wp_strpool_get(&doc.text, line->text);
                fwrite(text, 1, line->text.length, out);
                fputc('\n', out);
            } else {
                const u8 *label = wp_strpool_get(&doc.text, line->text);
                const u8 *target = wp_strpool_get(&doc.text, line->target);

                fputs("@{\"", out);
                write_escaped(out, label, line->text.length);
                fputs("\" link ", out);
                fwrite(target, 1, line->target.length, out);
                fputs("}\n", out);
            }
        }

        fputs("@endnode\n\n", out);
    }

    fclose(out);
    wp_help_doc_free(&doc);
    return 0;
}
