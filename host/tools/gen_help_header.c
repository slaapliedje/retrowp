#include <stdio.h>
#include <string.h>

/* Host-only build tool (M8.5 Phase 10): converts a docs/help/ *.help
   source file into a generated C header holding its raw bytes as a
   numeric array -- so RetroWP's help content ships compiled into every
   target (no runtime file dependency, unlike the optional spell
   dictionary at C:\WPSPELL.DIC) while still being authored as a real,
   human-editable text file, not a hand-escaped C string someone has to
   remember to keep in sync. A byte array (not a string literal) side-
   steps C string-escaping entirely -- no quote/backslash/control-
   character handling to get right here, and the content is genuinely
   binary-length-bounded UTF-8 the same way wp_strpool never relies on
   NUL termination either.

   Usage: gen_help_header <input.help> <output.h> <c_identifier>
   Mirrors this project's other host/tools/ *.c programs: plain C89,
   POSIX stdio only, built with the host cc under RELAXED_CFLAGS (see
   the Makefile), never cross-compiled for Atari -- this tool runs only
   as part of the host build, generating a header the Atari build then
   includes as ordinary source. */

int main(int argc, char **argv)
{
    FILE *in, *out;
    unsigned char buf[4096];
    size_t n;
    unsigned long total = 0;
    unsigned int col = 0;
    const char *ident;

    if (argc != 4) {
        fprintf(stderr, "usage: %s <input.help> <output.h> <c_identifier>\n", argv[0]);
        return 1;
    }
    ident = argv[3];

    in = fopen(argv[1], "rb");
    if (in == NULL) {
        fprintf(stderr, "gen_help_header: cannot open %s\n", argv[1]);
        return 1;
    }
    out = fopen(argv[2], "w");
    if (out == NULL) {
        fprintf(stderr, "gen_help_header: cannot open %s for writing\n", argv[2]);
        fclose(in);
        return 1;
    }

    fprintf(out, "/* Generated by host/tools/gen_help_header.c from %s -- do not edit by hand. */\n",
            argv[1]);
    fprintf(out, "static const unsigned char %s[] = {\n", ident);

    while ((n = fread(buf, 1, sizeof(buf), in)) > 0) {
        size_t i;
        for (i = 0; i < n; i++) {
            fprintf(out, "%u,", (unsigned int)buf[i]);
            col++;
            if (col == 20) { fputc('\n', out); col = 0; }
        }
        total += (unsigned long)n;
    }
    if (col > 0) fputc('\n', out);

    fprintf(out, "};\n");
    fprintf(out, "static const unsigned long %s_len = %luUL;\n", ident, total);

    fclose(in);
    fclose(out);
    return 0;
}
